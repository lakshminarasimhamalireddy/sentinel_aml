CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    customer_reference VARCHAR(255) NOT NULL UNIQUE,
    risk_rating VARCHAR(255),
    created_at TIMESTAMP(6)
);

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    account_number VARCHAR(255) NOT NULL UNIQUE,
    account_type VARCHAR(255),
    currency VARCHAR(255),
    opening_date DATE
);

CREATE TABLE aml_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account(id),
    transaction_type VARCHAR(255) NOT NULL,
    amount NUMERIC(19,2) NOT NULL,
    amount_in_inr NUMERIC(19,2) NOT NULL,
    currency VARCHAR(255) NOT NULL,
    transaction_time TIMESTAMP(6) NOT NULL,
    counterparty VARCHAR(255),
    jurisdiction VARCHAR(255),
    channel VARCHAR(255)
);

CREATE TABLE aml_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    account_id BIGINT NOT NULL REFERENCES account(id),
    rule_name VARCHAR(255) NOT NULL,
    risk_score INTEGER NOT NULL,
    status VARCHAR(255),
    explanation VARCHAR(3000),
    evidence_transaction_ids VARCHAR(2000),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    analyst_name VARCHAR(255),
    disposition_reason VARCHAR(255)
);

CREATE TABLE rule_config (
    rule_key VARCHAR(255) PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    value VARCHAR(255),
    risk_weight INTEGER NOT NULL
);

CREATE INDEX idx_aml_transaction_account_time ON aml_transactions(account_id, transaction_time);
CREATE INDEX idx_aml_alert_risk_score ON aml_alerts(risk_score DESC);
